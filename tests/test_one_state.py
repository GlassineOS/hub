"""Every action runs as a one-state workflow (012 FR-010): its launch is what it was when the action held its own rights.

one_state_launch.json holds, for each action, what the code made from the action files alone: the defaults, the preview
command, the resume command, the settings and hooks, the token's scope and what the app gets of its rights. Words a
session reads (prompts, personas, skills) and words the app shows are left out, so editing them changes nothing here, and
an action added later has no entry. It is not regenerated by the test: a change that means to start an action's sessions
differently edits its entry in the same commit, by hand or with launch() on a scratch state folder, and says why.
"""
import json
import shutil
import sys
from pathlib import Path

import pytest

from hubd import agents as agents_module
from hubd.agents import NO_REPO_OBJECTS, Agents, Library, LibraryError

REPO = Path(__file__).resolve().parents[1]
GOLDEN = Path(__file__).with_name("one_state_launch.json")


def _item(action: dict) -> tuple:
    if action["object"] in NO_REPO_OBJECTS:
        return None, None
    return ("boot", None) if action["object"] == "repo" else ("boot", 5)


def launch(library: Library, state: Path) -> dict:
    """What each action's session would start with, its paths as placeholders."""
    a = Agents(library, None, state, socket=state / "hubd.sock")
    out = {"actions": {str(kind): [{"id": row["id"], "full": row["full"]} for row in a.actions(kind)]
                       for kind in (None, *sorted({x["object"] for x in library.actions.values()}))}}
    for action_id, action in sorted(library.actions.items()):
        repo, number = _item(action)
        config = a.defaults(action_id, repo, number)
        directory = a.sessions / a._name(action, config, set())
        checkouts = a._checkouts(directory.name, config, action)
        checkout = checkouts[0][1] if checkouts else None
        out[action_id] = {
            "defaults": config, "advanced": {k: v for k, v in a.action(action_id).items() if k in ("tools", "hub_tools", "full", "checkout")},
            "preview": {k: v for k, v in a.preview(config).items() if k != "prompt"},
            "resume": a._argv(config, action, directory, checkout, "<id>", state / "hub-mcp.json", resume=True),
            "settings": a._hooks(directory, config, action),
            "scope": agents_module._session_scope(directory.name, config, agents_module._full(action), a._all_repos(config),
                                                  a._asks_first(config), "<instance>"),
            "full": agents_module._full(action), "mode": agents_module._mode(action), "ask_wait": a.ask_wait(action),
            "notes_search": agents_module._may_search_notes(action),
            "current": a._current_config({**config, "tools": [*config["tools"], "Write"], "hub_tools": [*config["hub_tools"], "merge_pr"]}),
        }
    text = json.dumps(out, indent=1, sort_keys=True, default=list)
    for real, placeholder in ((sys.executable, "<python>"), (str(state), "<state>"), (str(REPO), "<repo>")):  # the interpreter may be in the checkout
        text = text.replace(real, placeholder)
    return json.loads(text)


@pytest.fixture(autouse=True)
def sandbox_tools_present(monkeypatch):
    monkeypatch.setattr(agents_module, "SANDBOX_TOOLS", ())


def test_every_action_starts_as_it_did(tmp_path):
    got, want = launch(Library(REPO / "agents"), tmp_path), json.loads(GOLDEN.read_text())
    assert set(want) <= set(got), "an action is gone"
    known = set(want) - {"actions"}
    got = {**{k: got[k] for k in want}, "actions": {kind: [row for row in rows if row["id"] in known] for kind, rows in got["actions"].items()}}
    assert _differences(got, want) == []


def _differences(got, want, at="") -> list[str]:
    """Where two JSON values differ, as paths: an action's launch is too long to read as one assertion."""
    if isinstance(want, dict) and isinstance(got, dict):
        return [d for k in sorted(set(got) | set(want), key=str) for d in
                (_differences(got.get(k), want.get(k), f"{at}/{k}") if k in got and k in want else [f"{at}/{k}"])]
    if isinstance(want, list) and isinstance(got, list) and len(want) == len(got):
        return [d for i, (g, w) in enumerate(zip(got, want)) for d in _differences(g, w, f"{at}/{i}")]
    return [] if got == want else [f"{at}: {got!r} != {want!r}"[:400]]


def test_every_action_has_a_one_state_workflow_of_its_name():
    library = Library(REPO / "agents")
    for action_id, action in library.actions.items():
        assert action["workflow"] == action_id
        definition = library.workflows[action_id]
        assert len(definition.states) == 1 and definition.states[definition.initial].final, action_id


def _copy(tmp_path) -> Path:
    root = tmp_path / "agents"
    shutil.copytree(REPO / "agents", root)
    return root


def test_an_action_runs_under_the_workflow_it_names(tmp_path):
    root = _copy(tmp_path)
    path = root / "actions" / "pr-explain.toml"
    path.write_text('workflow = "pr-review"\n' + path.read_text())
    library = Library(root)
    assert library.action("pr-explain")["workflow"] == "pr-review"
    assert library.action("pr-explain")["grant"] == library.action("pr-review")["grant"]


@pytest.mark.parametrize("change, error", [
    (lambda r: _append(r / "actions" / "pr-explain.toml", 'access = "full"\n'), "access belong to its workflow"),
    (lambda r: _append(r / "actions" / "pr-explain.toml", 'tools = ["Read"]\n'), "tools belong to its workflow"),
    (lambda r: _append(r / "actions" / "pr-explain.toml", 'github = ["pr.read"]\n'), "github belong to its workflow"),
    (lambda r: (r / "workflows" / "pr-explain.toml").unlink(), "workflow 'pr-explain' isn't one of"),
    (lambda r: _edit(r / "workflows" / "pr-explain.toml", 'name = "pr-explain"', 'name = "pr-other"'), "not the file's"),
    (lambda r: _edit(r / "workflows" / "pr-explain.toml", 'checkout = "pr"', 'checkout = "main"'), "checkout"),
    (lambda r: _edit(r / "workflows" / "pr-explain.toml", "final = true", "final = false"), "isn't final and has no exit"),
    (lambda r: _append(r / "workflows" / "pr-explain.toml", '\n[state.more]\nfinal = true\n'), "can't be reached"),
])
def test_the_library_refuses_rights_out_of_place_and_a_broken_workflow(tmp_path, change, error):
    root = _copy(tmp_path)
    change(root)
    with pytest.raises(LibraryError, match=error):
        Library(root)


def test_a_workflow_with_more_states_loads_and_starts_in_its_first(tmp_path):
    root = _copy(tmp_path)
    _edit(root / "workflows" / "pr-explain.toml", "final = true", '[[state.session.exit]]\nto = "done"\ndecided_by = "hand"\n\n[state.done]\nfinal = true')
    library = Library(root)
    assert library.action("pr-explain")["grant"] == Library(REPO / "agents").action("pr-explain")["grant"]
    assert len(library.states_of(library.action("pr-explain"))) == 2


def test_the_notes_search_holds_for_every_state_a_session_can_move_to(tmp_path):
    """A session keeps what it read when it moves, so a state that can post can't follow one that reads the notes."""
    root = _copy(tmp_path)
    _edit(root / "workflows" / "knowledge-research.toml", "final = true",
          '[[state.session.exit]]\nto = "post"\ndecided_by = "hand"\n\n[state.post]\nfinal = true\n[state.post.grant]\nhub_tools = ["comment_issue"]')
    with pytest.raises(LibraryError, match="in every state"):
        Library(root)
    _edit(root / "workflows" / "knowledge-research.toml", 'hub_tools = ["comment_issue"]', 'hub_tools = ["docs_search"]')
    with pytest.raises(LibraryError, match="has notes_find in its hub_tools, in every state"):
        Library(root)


def _edit(path: Path, old: str, new: str) -> None:
    text = path.read_text()
    assert old in text
    path.write_text(text.replace(old, new))


def _append(path: Path, text: str) -> None:
    path.write_text(path.read_text() + text)
